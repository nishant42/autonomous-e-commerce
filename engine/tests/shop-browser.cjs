// Browser regression for the local Medusa demo. Creates a cart; never submits payment or an order.
// Run with NODE_PATH=/tmp/halden-ui-qa/node_modules node engine/tests/shop-browser.cjs
const {chromium}=require('playwright-core');
const assert=require('node:assert/strict');
const path=require('node:path');
const artifactPath=path.resolve(__dirname,'../../artifacts');
(async()=>{
 const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 page.on('pageerror',e=>console.log('PAGEERROR',e.message));
 await page.goto('http://127.0.0.1:8787',{waitUntil:'networkidle',timeout:60000});
 assert.ok(page.url().startsWith('http://localhost:8787'));console.log('PASS canonical demo address');
 const shop=page.frameLocator('#shop-frame');
 await shop.getByTestId('products-list').waitFor({state:'visible',timeout:45000});
 console.log('PASS catalogue loads',await shop.getByTestId('product-wrapper').count(),'products');
 await shop.getByTestId('nav-menu-button').click();
 await shop.getByTestId('nav-menu-popup').waitFor({state:'visible',timeout:5000});
 console.log('PASS embedded menu opens');
 await page.screenshot({path:path.join(artifactPath,'shop-menu-working.png')});
 await shop.getByTestId('close-menu-button').click();
 await shop.getByText('Medusa T-Shirt',{exact:true}).click();
 await shop.getByTestId('add-product-button').waitFor({state:'visible',timeout:45000});
 console.log('PRODUCT',await shop.getByTestId('product-availability').innerText());
 console.log('OPTIONS',await shop.locator('fieldset').innerText().catch(()=>''));
 console.log('RADIOS',await shop.locator('input[type=radio]').evaluateAll(es=>es.map(e=>({name:e.name,value:e.value,checked:e.checked}))));
 assert.ok(await shop.getByTestId('add-product-button').isEnabled());console.log('PASS in-stock variant can be added');
 await shop.getByTestId('add-product-button').click();
 await shop.getByTestId('add-product-button').waitFor({state:'visible',timeout:30000});
 await page.waitForTimeout(1500);
 assert.ok((await shop.locator('body').innerText()).includes('Cart (1)'));
 console.log('PASS browser cart updates to one item');
 await shop.getByTestId('option-button').filter({hasText:/^S$/}).click();
 await shop.getByTestId('option-button').filter({hasText:/^Black$/}).click();
 await shop.getByTestId('product-availability').filter({hasText:'Out of stock'}).waitFor({state:'visible',timeout:10000});
 assert.ok(await shop.getByTestId('add-product-button').isDisabled());
 console.log('PASS sold-out S / Black is blocked');
 await page.screenshot({path:path.join(artifactPath,'shop-out-of-stock-working.png')});
 await shop.getByTestId('option-button').filter({hasText:/^L$/}).click();
 await shop.getByTestId('option-button').filter({hasText:/^White$/}).click();
 await shop.getByTestId('product-availability').filter({hasText:'In stock'}).waitFor({state:'visible',timeout:10000});
 assert.ok(await shop.getByTestId('add-product-button').isEnabled());
 console.log('PASS switching back to L / White enables purchase');
 await page.frame({url:/localhost:8000/}).goto('http://localhost:8000/dk/cart',{waitUntil:'networkidle',timeout:45000});
 console.log('CART PAGE',(await shop.locator('body').innerText()).slice(0,1800));
 const checkout=shop.getByRole('link',{name:'Go to checkout',exact:true});
 await checkout.waitFor({state:'visible',timeout:10000});await checkout.click();
 await shop.getByTestId('submit-address-button').waitFor({state:'visible',timeout:45000});
 console.log('PASS checkout address form opens');
 await page.screenshot({path:path.join(artifactPath,'shop-product-working.png')});
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1});
