"""Render the last run as an HTML page, using the site's own stylesheet.

This is the operator's view: what the agents decided, why, what the gateway
did with each proposal, and what is waiting for a human. It is generated from
the database, so it cannot disagree with the audit trail.
"""
import html
import json
import os

from core import db, bus

OUT = os.path.join(os.path.dirname(__file__), "..", "engine-run.html")

HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Engine Run</title>
<link rel="stylesheet" href="assets/style.css">
<script src="assets/app.js"></script>
</head>
<body>
<main><div class="content">
<div class="eyebrow">Live output · generated by engine/run.py</div>
<h1>What the three agents decided on this run</h1>
<p class="lede">Every number on this page was produced by the engine in <code>engine/</code> from 90 days of
seeded history, then read back out of the database. Nothing here is written by hand: regenerate it with
<code>python3 run.py console</code>.</p>
"""

TAIL = """
<div class="callout info"><span class="t">How to reproduce this page</span>
<p><code>cd engine &amp;&amp; python3 run.py demo</code> prints the same decisions in the terminal with every
intermediate value; <code>python3 run.py console</code> regenerates this page. No dependencies, no API key
required. With <code>ANTHROPIC_API_KEY</code> set, the rationales are written by the model instead of the
template and the decisions are unchanged.</p></div>
</div></main>
</body>
</html>
"""


def esc(v):
    return html.escape(str(v))


def table(headers, rows, widths=None):
    out = ['<div class="table-wrap"><table><tr>']
    out += ["<th>%s</th>" % esc(h) for h in headers]
    out.append("</tr>")
    for r in rows:
        out.append("<tr>" + "".join("<td>%s</td>" % c for c in r) + "</tr>")
    out.append("</table></div>")
    return "".join(out)


def status_tag(status):
    cls = {"executed": "ok", "pending_checker": "warn", "pending_human": "warn", "rejected": "bad"}.get(status, "")
    tag = {"executed": "buy", "pending_human": "med", "pending_checker": "med", "rejected": "hi"}.get(status, "det")
    return '<span class="tag %s">%s</span>' % (tag, esc(status))


def render(conn, reorder_out, marketing_out, weekly_out, verdict_out):
    p = [HEAD]

    # ---- reorder -----------------------------------------------------------
    p.append("<h2>1 · Reorder: the white and black towel case</h2>")
    p.append("<p>Both colours shipped twenty units in ninety days. The report a buyer reads stops there. "
             "These are the rows the engine derives before it proposes a quantity.</p>")
    pc = lambda v: "%.0f%%" % (v * 100)            # noqa: E731
    keys = [("units_shipped", "units shipped (90d)", None),
            ("available_days", "days actually buyable", None),
            ("ros_per_available_day", "rate of sale / available day", None),
            ("substitution_share", "substitution share removed", pc),
            ("avg_discount_pct", "avg discount on sales", lambda v: "%.0f%%" % v),
            ("price_factor", "price adjustment factor", None),
            ("return_rate", "return rate", pc),
            ("reconstructed_demand_period", "reconstructed demand (90d)", None),
            ("censored_gap", "demand hidden by stockouts", None),
            ("unmet_signal_lower_bound", "unmet-signal lower bound", None)]
    live = [x for x in reorder_out if not x.get("blocked")]
    rows = []
    for key, label, fmt in keys:
        rows.append(["<strong>%s</strong>" % esc(label)]
                    + [esc((fmt or str)(x["reconstruction"][key])) for x in live])
    dkeys = [("service_level", "derived service level (from Cu/Co)"), ("protection_interval_days", "protection interval (days)"),
             ("demand_mu", "demand over interval (mean)"), ("demand_sd", "demand over interval (sd)"),
             ("order_up_to", "order-up-to level"), ("on_hand", "on hand"),
             ("qty", "ORDER QUANTITY"), ("cover_after_weeks", "cover after arrival (weeks)"),
             ("capital_eur", "capital committed (EUR)")]
    for key, label in dkeys:
        bold = key == "qty"
        if key == "service_level":
            cells = ["%.0f%%" % (x["decision"][key] * 100) for x in live]
            rows.append([esc(label)] + cells)
            continue
        cells = [("<strong>%s</strong>" if bold else "%s") % esc(x["decision"][key]) for x in live]
        rows.append([("<strong>%s</strong>" if bold else "%s") % esc(label)] + cells)
    rows.append(["<strong>gateway</strong>"] + ["%s %s" % (status_tag(x["ledger"]["status"]),
                                                          esc(x["ledger"]["reason"])) for x in live])
    p.append(table(["line"] + [x["variant_id"] for x in live], rows))
    p.append('<div class="callout danger"><span class="t">The decision</span><p>Human, reading twenty and twenty: '
             '<strong>40 white, 0 black</strong>. Engine, reading the same period: <strong>%s</strong>.</p></div>'
             % esc(", ".join("%s %s" % (x["decision"]["qty"], x["variant_id"]) for x in live)))
    for x in live:
        p.append('<p class="caption"><code>%s</code> &mdash; %s</p>' % (esc(x["variant_id"]), esc(x["rationale"])))

    # ---- marketing ---------------------------------------------------------
    m = marketing_out
    p.append("<h2>2 · Marketing allocation: the daily pass</h2>")
    p.append('<div class="grid g4">'
             '<div class="stat"><div class="l">target CPA</div><div class="v">EUR %.2f</div></div>'
             '<div class="stat"><div class="l">signal drift</div><div class="v">%s%%</div></div>'
             '<div class="stat"><div class="l">organic share (holdout)</div><div class="v">%.0f%%</div></div>'
             '<div class="stat"><div class="l">experiment budget left</div><div class="v">EUR %.0f</div></div>'
             "</div>"
             % (m["target_cpa"], m["signal"]["drift_pct"], (m["holdout"]["organic_share"] or 0) * 100,
                m["budget"]["allocated_eur"] - m["budget"]["spent_eur"]))
    rows = []
    for c in m["cells"]:
        rows.append([esc(c["cell"]), esc(c["platform"]), "%.0f" % c["spend"], esc(c["orders"]),
                     esc("%.0f" % c["cpa"]) if c["cpa"] else "&ndash;",
                     "<strong>%s</strong>" % esc(c["action"]),
                     "%.0f &rarr; %.0f" % (c["from_eur"], c["to_eur"]),
                     esc(c["reason"])])
    p.append(table(["cell", "platform", "spend 7d", "orders", "CPA", "action", "daily budget", "rule that fired"], rows))
    if weekly_out:
        rows = [[esc(a), "%.1f%%" % (weekly_out["before"].get(a, 0) * 100), "%.1f%%" % (weekly_out["after"][a] * 100)]
                for a in sorted(weekly_out["after"], key=lambda x: -weekly_out["after"][x])]
        p.append("<h3>Weekly channel reallocation (Thompson sampling on profit per euro)</h3>")
        p.append(table(["arm", "share before", "share after"], rows))

    # ---- verdicts ----------------------------------------------------------
    p.append("<h2>3 · Product verdict: product or site, keep or kill</h2>")
    for v in verdict_out:
        d, r = v["diagnosis"], v["rates"]
        p.append('<div class="card"><h3>%s &mdash; %s <span class="tag %s">confidence %.0f%%</span></h3>'
                 % (esc(v["product_id"]), esc(d["verdict"]),
                    "buy" if d["confidence"] > 0.7 else "med", d["confidence"] * 100))
        rows = [[esc(k), "%.2f%%" % (r[k] * 100), esc(d["flags"][k])]
                for k in ("pdp_rate", "atc_rate", "checkout_rate", "purchase_rate", "refund_rate", "ctr")]
        rows.append(["CPA", esc(r["cpa"]), "target %s" % esc(v["target_cpa"])])
        p.append(table(["stage rate", "value", "band"], rows))
        p.append("<p><strong>Diagnosis:</strong> %s</p>" % esc(d["diagnosis"]))
        if d["findings"]:
            p.append("<ul>" + "".join("<li><strong>[%s]</strong> %s</li>" % (esc(f["owner"]), esc(f["finding"]))
                                      for f in d["findings"]) + "</ul>")
        if d["actions"]:
            p.append("<p><strong>Ranked actions:</strong></p><ul>"
                     + "".join("<li>%s</li>" % esc(a) for a in d["actions"]) + "</ul>")
        p.append("<p>Gateway: %s %s</p>" % (status_tag(v["ledger"]["status"]), esc(v["ledger"]["reason"])))
        if v["runbook"]:
            p.append("<p><strong>Kill runbook (held for a human):</strong></p><ul>"
                     + "".join("<li>%s</li>" % esc(s) for s in v["runbook"]) + "</ul>")
        p.append("</div>")

    # ---- platform ----------------------------------------------------------
    p.append("<h2>4 · The platform underneath</h2>")
    rows = [[esc(r["agent"]), esc(r["trigger"]), esc(r["steps"]), esc(r["tokens"]),
             esc(round(r["cost_eur"] or 0, 4)), esc(r["mode"]), esc(r["outcome"])]
            for r in db.rows(conn, "SELECT * FROM agent_run ORDER BY started_at")]
    p.append("<h3>Agent runs</h3>")
    p.append(table(["agent", "trigger", "steps", "tokens", "cost EUR", "mode", "outcome"], rows))
    q = bus.depth(conn)
    p.append('<p class="caption">Queue: %s ready, %s running, %s done, %s dead. '
             "%s tool results stored as evidence.</p>"
             % (q["ready"], q["running"], q["done"], q["dead"],
                db.scalar(conn, "SELECT COUNT(*) FROM evidence")))

    rows = [[esc(a["severity"]), esc(a["kind"]), esc(a["note"])]
            for a in db.rows(conn, "SELECT * FROM anomaly ORDER BY id")]
    if rows:
        p.append("<h3>Anomalies raised</h3>")
        p.append(table(["severity", "kind", "note"], rows))

    p.append("<h3>Ledger: every side effect, with its tier and reason</h3>")
    rows = []
    for r in db.rows(conn, "SELECT * FROM ledger ORDER BY id"):
        payload = json.loads(r["payload"])
        ev = json.loads(r["evidence"] or "[]")
        rows.append([esc(r["id"]), esc(r["agent"]), esc(r["intent"]),
                     esc(round(r["value_eur"] or 0, 2)), esc(r["tier"] or "&ndash;"),
                     status_tag(r["status"]), esc(r["reason"]),
                     "<code>%s</code>" % esc(json.dumps(payload)),
                     esc(len(ev))])
    p.append(table(["#", "agent", "intent", "EUR", "tier", "status", "reason", "payload", "evidence"], rows))
    p.append(TAIL)
    return "".join(p)


def write(conn, reorder_out, marketing_out, weekly_out, verdict_out):
    with open(OUT, "w") as fh:
        fh.write(render(conn, reorder_out, marketing_out, weekly_out, verdict_out))
    return os.path.abspath(OUT)
